-- PostgreSQL DDL for CommunityTopicRadar.
-- Run with: psql "$DATABASE_URL" -f sql/schema.sql

CREATE TABLE IF NOT EXISTS posts (
    id                  INTEGER PRIMARY KEY,
    title               VARCHAR(500) NOT NULL,
    body_text           TEXT,
    author_id           INTEGER,
    author_name         VARCHAR(255),
    created_at          TIMESTAMPTZ NOT NULL,
    score               INTEGER NOT NULL DEFAULT 0,
    view_count          INTEGER NOT NULL DEFAULT 0,
    answer_count        INTEGER NOT NULL DEFAULT 0,
    is_answered         BOOLEAN NOT NULL DEFAULT FALSE,
    accepted_answer_id  INTEGER,
    url                 VARCHAR(1000),
    source_site         VARCHAR(100) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_posts_created_at ON posts (created_at);
CREATE INDEX IF NOT EXISTS ix_posts_is_answered ON posts (is_answered);

CREATE TABLE IF NOT EXISTS tags (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS post_tags (
    post_id INTEGER NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    tag_id  INTEGER NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (post_id, tag_id)
);

CREATE TABLE IF NOT EXISTS authors (
    id             INTEGER PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    reputation     INTEGER NOT NULL DEFAULT 0,
    first_seen_at  TIMESTAMPTZ NOT NULL,
    last_seen_at   TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS engagement_daily (
    day              DATE NOT NULL,
    source_site      VARCHAR(100) NOT NULL,
    posts_created    INTEGER NOT NULL DEFAULT 0,
    answers_created  INTEGER NOT NULL DEFAULT 0,
    unique_authors   INTEGER NOT NULL DEFAULT 0,
    answered_count   INTEGER NOT NULL DEFAULT 0,
    total_views      INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (day, source_site)
);
